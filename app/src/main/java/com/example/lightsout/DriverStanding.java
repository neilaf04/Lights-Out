package com.example.lightsout;

public class DriverStanding {

    String position;
    String driverName;
    String teamName;
    String points;

    public DriverStanding(String position, String driverName, String teamName, String points) {
        this.position = position;
        this.driverName = driverName;
        this.teamName = teamName;
        this.points = points;
    }
}